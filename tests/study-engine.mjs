import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context={window:{},Date,Math};vm.createContext(context);
for(const file of ['rationales.js','data.js','study-engine.js'])vm.runInContext(readFileSync(new URL(`../${file}`,import.meta.url),'utf8'),context);
const D=context.window.OIC_DATA,E=context.window.OIC_ENGINE;
const assert=(condition,message)=>{if(!condition)throw new Error(message)};
const multi=D.questions.find(q=>q.multi);
assert(multi,'Expected at least one multi-answer question');
assert(E.score(multi,multi.correct),'Multiple-answer scoring should accept exactly the correct set');
assert(!E.score(multi,[multi.correct[0]]),'Multiple-answer scoring must reject partial selections');
const first=E.grade({},5,0),second=E.grade(first,5,86400000);
assert(first.interval===1&&second.interval===6,'SM-2 intervals should grow after repeated successful recall');
const fail=E.grade(second,1,86400000*2);
assert(fail.repetitions===0&&fail.interval===1,'A failed recall should reset the repetition interval');
const a=E.examDistribution(D.questions,E.createRng(12345));
const b=E.examDistribution(D.questions,E.createRng(12345));
assert(a.map(q=>q.id).join('|')===b.map(q=>q.id).join('|'),'Seeded exam selection should be reproducible');
const expected={started:7,connections:10,orchestration:16,scheduled:5,monitoring:6,ai:6};
for(const [id,count] of Object.entries(expected))assert(a.filter(q=>q.categoryId===id).length===count,`Exam distribution mismatch for ${id}`);
const split=E.selection(D.questions,10,'split',{},E.createRng(3));
assert(split.length===10&&split.filter(q=>q.difficulty==='professional').length===5&&split.filter(q=>q.difficulty==='expert').length===5,'Quick split must have five questions at each difficulty');
assert(new Set(split.map(q=>q.id)).size===10,'Quick round must not repeat questions');
const sample=D.questions.slice(0,3),history={[sample[0].id]:{correct:true},[sample[1].id]:{correct:true,everIncorrect:true}};
const unanswered=E.selection(sample,10,'unanswered',history,E.createRng(1),[sample[0].id,sample[2].id]);
const fresh=E.selection(sample,10,'new',history,E.createRng(1),[sample[0].id,sample[2].id]);
const incorrect=E.selection(sample,10,'incorrect',history,E.createRng(1));
assert(unanswered.length===1&&unanswered[0].id===sample[2].id,'Unanswered should include a seen but skipped question');
assert(fresh.length===1&&fresh[0].id===sample[1].id,'New should mean never shown, even if answered history differs');
assert(incorrect.length===1&&incorrect[0].id===sample[1].id,'Previously incorrect should retain corrected misses');
const imported={id:'private-1',categoryId:'started',question:'Example?',options:[{id:'A',text:'Yes'},{id:'B',text:'No'}],correct:['A'],verification:'unverified',reference:[{url:'https://docs.oracle.com/example'}]};
const pending=E.normalizeImportedQuestion(imported,'local.json');
assert(pending.correct.length===0&&pending.options.every(o=>!o.correct)&&pending.sourceType==='private-import','Unverified private answers must not enter scored practice or reveal a key');
const verified=E.normalizeImportedQuestion({...imported,verification:'verified'},'local.json');
assert(verified.correct[0]==='A'&&verified.options[0].correct&&verified.reference.url==='https://docs.oracle.com/example','Verified imported key and reference should be normalized for the app');
const badKey=E.normalizeImportedQuestion({...imported,verification:'verified',correct:['C']},'local.json');
assert(badKey.verification==='requires review'&&badKey.correct.length===0,'A verified label with an invalid answer key must be rejected');
console.log('Study engine validation passed.');
